private func fixture(_ name: String, _ ext: String) throws -> URL {
    try XCTUnwrap(Bundle(for: NormalizerTests.self).url(forResource: name, withExtension: ext))
}

final class NormalizerTests: XCTestCase {
    func testBasics() {
        XCTAssertEqual(Normalizer.normalize("Café"), "cafe")
        XCTAssertEqual(Normalizer.normalize("  don’t   stop "), "don't stop")
        XCTAssertEqual(Normalizer.normalize("NAÏVE"), "naive")
    }

    func testKeepsSeparateCyrillicLetters() {
        XCTAssertEqual(Normalizer.normalize("Мій"), "мій")
        XCTAssertEqual(Normalizer.normalize("Їжак"), "їжак")
        XCTAssertEqual(Normalizer.normalize("сло́во"), "слово")
        XCTAssertEqual(Normalizer.normalize("мі\u{306}й"), "мій")
        XCTAssertEqual(Normalizer.normalize("niño"), "nino")
    }

    /// Cases generated by pipeline/build.py `normalize()` from real headwords;
    /// the app's search keys must match the ones in the database.
    func testMatchesPipeline() throws {
        let data = try Data(contentsOf: fixture("normalize_cases", "json"))
        let cases = try JSONDecoder().decode([[String]].self, from: data)
        XCTAssertGreaterThan(cases.count, 1000)
        let mismatches = cases.filter { Normalizer.normalize($0[0]) != $0[1] }
        XCTAssert(mismatches.isEmpty, "Mismatches: \(mismatches.prefix(10))")
    }
}

final class DictionaryDatabaseTests: XCTestCase {
    private var database: DictionaryDatabase!

    override func setUpWithError() throws {
        database = try DictionaryDatabase(url: fixture("fixture", "sqlite"))
    }

    func testMeta() {
        XCTAssertEqual(database.entryCount, 3)
    }

    func testPrefixSearch() throws {
        let results = try database.search("fre")
        XCTAssertEqual(results.map(\.word), ["free"])
        XCTAssertEqual(results.first?.partsOfSpeech, ["adj"])
        XCTAssertEqual(results.first?.gloss, "Not imprisoned or enslaved.")
    }

    func testSearchThroughForm() throws {
        let results = try database.search("freer")
        XCTAssertEqual(results.first?.word, "free")
        XCTAssertEqual(results.first?.matchedForm, "freer")
    }

    func testSearchIgnoresAccentsAndCase() throws {
        XCTAssertEqual(try database.search("CAFE").map(\.word), ["Café"])
    }

    func testEmptyQuery() throws {
        XCTAssertEqual(try database.search("   "), [])
    }

    func testEntries() throws {
        let entries = try database.entries(for: "went")
        XCTAssertEqual(entries.count, 1)
        XCTAssertEqual(entries[0].data.senses[0].targets, ["go"])
        XCTAssertEqual(try database.entries(for: "nope"), [])
    }
}

final class OutlineTests: XCTestCase {
    private func data(_ json: String) throws -> EntryData {
        try JSONDecoder().decode(EntryData.self, from: Data(json.utf8))
    }

    func testSubsensesAreLettered() throws {
        let entry = try data("""
        {"senses": [
          {"glosses": ["Unconstrained."], "qualifier": "social"},
          {"glosses": ["Unconstrained.", "Not imprisoned."], "qualifier": "social"},
          {"glosses": ["Unconstrained.", "Generous."], "qualifier": "social", "tags": ["obsolete"]},
          {"glosses": ["Costing nothing."]}
        ]}
        """)
        let outline = entry.outline()
        XCTAssertEqual(outline.map(\.number), ["1", "1a", "1b", "2"])
        XCTAssertEqual(outline.map(\.gloss), ["Unconstrained.", "Not imprisoned.", "Generous.", "Costing nothing."])
        XCTAssertEqual(outline[1].labels, [])          // "social" already on the parent
        XCTAssertEqual(outline[2].labels, ["obsolete"])
    }

    func testParentWithoutOwnSenseGetsHeading() throws {
        let entry = try data("""
        {"senses": [{"glosses": ["Parent.", "Child one."]}, {"glosses": ["Parent.", "Child two."]}]}
        """)
        let outline = entry.outline()
        XCTAssertEqual(outline.map(\.number), ["1", "1a", "1b"])
        XCTAssertNil(outline[0].sense)
    }

    func testFormOfHidesGrammaticalTags() throws {
        let entry = try data("""
        {"senses": [{"glosses": ["past of go"], "tags": ["form-of", "past", "archaic"], "form_of": ["go"]}]}
        """)
        XCTAssertEqual(entry.senses[0].labels, ["archaic"])
    }

    func testPrefersBroadIPA() throws {
        let entry = try data("""
        {"senses": [], "ipa": [{"ipa": "/fɹiː/"}, {"ipa": "[fɹɪi̯]"}]}
        """)
        XCTAssertEqual(entry.displayIPA.map(\.ipa), ["/fɹiː/"])
    }
}

final class InstallerTests: XCTestCase {
    func testDecompressAndChecksum() throws {
        // Real xz files from the pipeline are covered by the end-to-end download check;
        // this round-trips through Apple's LZMA (xz container) encoder.
        let source = try fixture("fixture", "sqlite")
        let tmp = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: tmp, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: tmp) }

        let compressed = tmp.appendingPathComponent("fixture.sqlite.xz")
        let original = try Data(contentsOf: source)
        try compressLZMA(original).write(to: compressed)

        let output = tmp.appendingPathComponent("out.sqlite")
        try Installer.decompress(compressed, to: output)
        XCTAssertEqual(try Installer.sha256(of: output), try Installer.sha256(of: source))
    }

    private func compressLZMA(_ data: Data) throws -> Data {
        var result = Data()
        let filter = try OutputFilter(.compress, using: .lzma) { chunk in if let chunk { result.append(chunk) } }
        try filter.write(data)
        try filter.finalize()
        return result
    }
}

@MainActor
final class RecentWordsTests: XCTestCase {
    private var defaults: UserDefaults!

    override func setUp() {
        defaults = UserDefaults(suiteName: "RecentWordsTests-\(UUID().uuidString)")
    }

    private func word(_ w: String) -> RecentWord {
        RecentWord(word: w, partsOfSpeech: ["noun"], gloss: "gloss of \(w)")
    }

    func testNewestFirstWithoutDuplicates() {
        let recents = RecentWords(defaults: defaults)
        recents.load(lang: "en")
        recents.add(word("free"))
        recents.add(word("went"))
        recents.add(word("free"))
        XCTAssertEqual(recents.items.map(\.word), ["free", "went"])
    }

    func testLimit() {
        let recents = RecentWords(defaults: defaults)
        recents.load(lang: "en")
        for i in 0..<(RecentWords.limit + 5) { recents.add(word("w\(i)")) }
        XCTAssertEqual(recents.items.count, RecentWords.limit)
        XCTAssertEqual(recents.items.first?.word, "w\(RecentWords.limit + 4)")
    }

    func testPersistsPerDictionary() {
        let recents = RecentWords(defaults: defaults)
        recents.load(lang: "en")
        recents.add(word("free"))
        recents.load(lang: "de")
        XCTAssertEqual(recents.items, [])
        recents.add(word("frei"))

        let reloaded = RecentWords(defaults: defaults)
        reloaded.load(lang: "en")
        XCTAssertEqual(reloaded.items.map(\.word), ["free"])
        reloaded.load(lang: "de")
        XCTAssertEqual(reloaded.items.map(\.word), ["frei"])
    }

    func testRemoveAndClear() {
        let recents = RecentWords(defaults: defaults)
        recents.load(lang: "en")
        ["a", "b", "c"].forEach { recents.add(word($0)) }
        recents.remove(atOffsets: IndexSet(integer: 1))
        XCTAssertEqual(recents.items.map(\.word), ["c", "a"])
        recents.clear()
        XCTAssertEqual(recents.items, [])
    }
}
