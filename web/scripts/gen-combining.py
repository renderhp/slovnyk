"""Writes src/lib/combining.ts: code point ranges with a non-zero canonical
combining class, i.e. exactly what pipeline/build.py's normalize() strips."""
import unicodedata
from pathlib import Path

ranges, start, prev = [], None, None
for cp in range(0x110000):
    if unicodedata.combining(chr(cp)):
        if start is None:
            start = cp
        elif cp != prev + 1:
            ranges.append((start, prev))
            start = cp
        prev = cp
ranges.append((start, prev))

flat = ",".join(f"0x{a:x},0x{b:x}" for a, b in ranges)
out = Path(__file__).resolve().parents[1] / "src/lib/combining.ts"
out.write_text(
    "// Generated by scripts/gen-combining.py (Unicode %s). Do not edit.\n"
    "// Pairs of [start, end] code points with a non-zero canonical combining class.\n"
    "export const COMBINING_RANGES = new Uint32Array([%s]);\n" % (unicodedata.unidata_version, flat)
)
print(f"{len(ranges)} ranges -> {out}")
